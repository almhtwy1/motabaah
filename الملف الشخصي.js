    const getPinned = () => { try { return JSON.parse(localStorage.getItem(PIN_KEY) || '[]'); } catch(e) { return []; } };
    const getIdMap = () => { try { return JSON.parse(localStorage.getItem(ID_MAP_KEY) || '{}'); } catch(e) { return {}; } };
    const getPinRef = (r) => r?.dataset?.pinId || '';
    const getPinTransKey = (r) => (r?.cells?.[2]?.title || '') + '|' + (r?.cells?.[3]?.textContent?.trim() || '');

    function refreshPinning() {
        if (localStorage.getItem(STORAGE_KEY_PINNING) !== 'enabled') return;
        const tbody = document.querySelector('#MailDataTable tbody');
        if (!tbody || !originalOrder.length) return;
        const pinnedIds = getPinned();
        const rows = [...tbody.rows];
        rows.sort((a, b) => {
            const idA = getPinRef(a), idB = getPinRef(b);
            const idxA = pinnedIds.indexOf(idA), idxB = pinnedIds.indexOf(idB);
            if (idxA !== -1 && idxB !== -1) return idxA - idxB;
            if (idxA !== -1) return -1;
            if (idxB !== -1) return 1;
            return originalOrder.indexOf(idA) - originalOrder.indexOf(idB);
        });
        rows.forEach(r => {
            tbody.appendChild(r);
            const isPinned = pinnedIds.includes(getPinRef(r));
            r.classList.toggle('p-row', isPinned);
            const s = r.querySelector('.p-star');
            if (s) { s.classList.toggle('on', isPinned); s.title = isPinned ? 'إلغاء' : 'تثبيت'; }
        });
    }

    function initPinEngine() {
        const pinningEnabled = localStorage.getItem(STORAGE_KEY_PINNING) === 'enabled';
        if (!pinningEnabled) {
            document.querySelectorAll('.p-star').forEach(el => el.remove());
            document.querySelectorAll('.p-row').forEach(el => el.classList.remove('p-row'));
            if (originalOrder.length > 0) {
                const tbody = document.querySelector('#MailDataTable tbody');
                if (tbody) {
                    const rows = [...tbody.rows];
                    rows.sort((a, b) => {
                        const idA = getPinRef(a) || getPinTransKey(a);
                        const idB = getPinRef(b) || getPinTransKey(b);
                        return originalOrder.indexOf(idA) - originalOrder.indexOf(idB);
                    });
                    rows.forEach(r => tbody.appendChild(r));
                }
            }
            return;
        }

        if (pinBusy) return;
        pinBusy = true;

        const rows = document.querySelectorAll('#MailDataTable tbody tr');
        if (!rows.length) { pinBusy = false; return; }

        if (originalOrder.length === 0 || originalOrder.length !== rows.length) {
            originalOrder = Array.from(rows).map(r => getPinRef(r) || getPinTransKey(r));
        }

        let needsIdMapSave = false;
        const idMap = getIdMap();

        rows.forEach((row, index) => {
            const transKey = getPinTransKey(row);

            if (!row.dataset.pinId) {
                row.dataset.pinId = idMap[transKey] || (Date.now() + '_' + Math.random());
                if (!idMap[transKey]) {
                    idMap[transKey] = row.dataset.pinId;
                    needsIdMapSave = true;
                }
            }

            originalOrder[index] = row.dataset.pinId;

            if (row.querySelector('.p-star')) return;
            const star = document.createElement('span');
            star.className = 'p-star';
            star.textContent = '★';
            star.onclick = (e) => {
                e.stopPropagation();
                let list = getPinned();
                const id = getPinRef(row);
                list = list.includes(id) ? list.filter(x => x !== id) : [id, ...list];
                localStorage.setItem(PIN_KEY, JSON.stringify(list));
                refreshPinning();
            };
            if (row.cells[1]) {
                row.cells[1].style.position = 'relative';
                row.cells[1].style.paddingInlineEnd = '26px';
                row.cells[1].appendChild(star);
            }
        });

        if (needsIdMapSave) {
            localStorage.setItem(ID_MAP_KEY, JSON.stringify(idMap));
        }

        refreshPinning();
        pinBusy = false;
    }

