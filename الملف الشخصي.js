    function formatHijriReverse(str) {
        if (!str) return str;
        return str.replace(/(\d{1,4})[-/](\d{1,2})[-/](\d{1,4})/g, (match, p1, p2, p3) => {
            let day, month, year;
            if (p1.length === 4 || parseInt(p1, 10) > 1300) {
                year = p1; month = p2.padStart(2, '0'); day = p3.padStart(2, '0');
            } else {
                day = p1.padStart(2, '0'); month = p2.padStart(2, '0'); year = p3;
            }
            return `${year}/${month}/${day}`;
        });
    }

    function hijriToGregorian(d, m, y) {
        try {
            const day = parseInt(d, 10), month = parseInt(m, 10), year = parseInt(y, 10);
            if (day < 1 || day > 30 || month < 1 || month > 12 || year < 1300 || year > 1500) return null;

            let jd = Math.floor((11 * year + 3) / 30) + 354 * year + 30 * month - Math.floor((month - 1) / 2) + day + 1948440 - 385;
            let l = jd + 68569;
            const n = Math.floor((4 * l) / 146097);
            l = l - Math.floor((146097 * n + 3) / 4);
            const i = Math.floor((4000 * (l + 1)) / 1461001);
            l = l - Math.floor((1461 * i) / 4) + 31;
            const j = Math.floor((80 * l) / 2447);

            const gDay = l - Math.floor((2447 * j) / 80);
            l = Math.floor(j / 11);
            const gMonth = j + 2 - 12 * l;
            const gYear = 100 * (n - 49) + i + l;

            try {
                let estDate = new Date(Date.UTC(gYear, gMonth - 1, gDay, 12, 0, 0));
                const formatter = new Intl.DateTimeFormat('en-US-u-ca-islamic-umalqura-nu-latn', {
                    timeZone: 'UTC', year: 'numeric', month: 'numeric', day: 'numeric'
                });

                const safeParse = (str) => parseInt(String(str).replace(/[^\d\u0660-\u0669\u06f0-\u06f9]/g, '').replace(/[\u0660-\u0669\u06f0-\u06f9]/g, c => c.charCodeAt(0) & 15), 10);

                for (let offset = -5; offset <= 5; offset++) {
                    let testDate = new Date(estDate.getTime() + offset * 86400000);
                    let parts = formatter.formatToParts(testDate);

                    let hYearPart = parts.find(p => p.type === 'year' || p.type === 'relatedYear');
                    let hMonthPart = parts.find(p => p.type === 'month');
                    let hDayPart = parts.find(p => p.type === 'day');

                    if (hYearPart && hMonthPart && hDayPart) {
                        let hYear = safeParse(hYearPart.value);
                        let hMonth = safeParse(hMonthPart.value);
                        let hDay = safeParse(hDayPart.value);

                        if (hYear === year && hMonth === month && hDay === day) {
                            return `${testDate.getUTCFullYear()}/${String(testDate.getUTCMonth() + 1).padStart(2, '0')}/${String(testDate.getUTCDate()).padStart(2, '0')}`;
                        }
                    }
                }
            } catch (err) {
                // Ignore Intl errors and fallback
            }

            // Fallback: The tabular formula is usually 1 day ahead for Saudi Arabia, so we subtract 1 day
            let fbDate = new Date(Date.UTC(gYear, gMonth - 1, gDay - 1, 12, 0, 0));
            return `${fbDate.getUTCFullYear()}/${String(fbDate.getUTCMonth() + 1).padStart(2, '0')}/${String(fbDate.getUTCDate()).padStart(2, '0')}`;
        } catch (e) {
            return null;
        }
    }

    function parseText(str) {
        if (!str) return null;
        const cleanStr = str.replace(/\s+/g, '').trim();
        const match = cleanStr.match(/(\d{1,2})[-/](\d{1,2})[-/](14\d{2})/) || cleanStr.match(/(14\d{2})[-/](\d{1,2})[-/](\d{1,2})/);
        if (match) {
            return match[3].length === 4
                ? hijriToGregorian(match[1], match[2], match[3])
                : hijriToGregorian(match[3], match[2], match[1]);
        }
        return null;
    }

    function processRow(row, isGregorian) {
        let hasHijri = false;
        let hasGregorian = false;
        Array.from(row.cells).forEach(cell => {
            if (!cell || cell.querySelector('input, a, .p-star, i, img, button')) return;
            const txt = cell.dataset.originalText || cell.textContent.trim();
            if (txt.match(/\d{1,2}[-/]\d{1,2}[-/]14\d{2}/) || txt.match(/14\d{2}[-/]\d{1,2}[-/]\d{1,2}/)) hasHijri = true;
            if (txt.match(/\d{1,2}[-/]\d{1,2}[-/]20\d{2}/) || txt.match(/20\d{2}[-/]\d{1,2}[-/]\d{1,2}/)) hasGregorian = true;
        });

        const preventConversion = hasHijri && hasGregorian;

        Array.from(row.cells).forEach(cell => {
            if (!cell || cell.querySelector('input, a, .p-star, i, img, button')) return;

            const trimmedText = cell.textContent.trim();
            if (!trimmedText.match(/\d{1,2}[-/]\d{1,2}[-/](14|20)\d{2}/) && !trimmedText.match(/(14|20)\d{2}[-/]\d{1,2}[-/]\d{1,2}/)) return;

            if (!cell.dataset.originalText) {
                cell.dataset.originalText = trimmedText;
            }

            const rawText = cell.dataset.originalText;

            if (isGregorian && !preventConversion && rawText.includes('14')) {
                if (cell.dataset.converted === "true") return;
                let updatedText = rawText.replace(/(\d{1,2})[-/](\d{1,2})[-/](14\d{2})/g, (m, d, mo, y) => hijriToGregorian(d, mo, y) || m)
                                         .replace(/(14\d{2})[-/](\d{1,2})[-/](\d{1,2})/g, (m, y, mo, d) => hijriToGregorian(d, mo, y) || m);
                if (updatedText !== rawText) {
                    cell.textContent = updatedText;
                    if (cell.hasAttribute('title')) cell.setAttribute('title', updatedText);
                    cell.style.direction = 'ltr';
                    cell.dataset.converted = "true";
                }
            } else {
                const formattedDate = formatHijriReverse(rawText);
                if (cell.textContent !== formattedDate) {
                    cell.textContent = formattedDate;
                    cell.style.direction = 'ltr';
                    cell.style.unicodeBidi = 'bidi-override';
                    if (cell.hasAttribute('title')) cell.setAttribute('title', formattedDate);
                    delete cell.dataset.converted;
                }
            }
        });
    }

